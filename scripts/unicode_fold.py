"""Regenerate the pinned Unicode simple-fold table, offline and reproducibly."""
import hashlib
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT/'scripts/data/CaseFolding-16.0.0.txt'
SHA256 = '6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb'

def generate():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('unexpected Unicode source digest')
    mapping = {}
    for line in raw.decode().splitlines():
        fields = line.split('#')[0].split(';')
        if len(fields) >= 3 and fields[1].strip() in ('C', 'S'):
            mapping[int(fields[0], 16)] = int(fields[2], 16)
    points = sorted(mapping)
    ranges = []
    i = 0
    while i < len(points):
        first = last = points[i]
        delta = mapping[first] - first
        step = points[i+1] - first if i+1 < len(points) else 1
        if step not in (1, 2): step = 1
        j = i+1
        while j < len(points) and points[j] == last+step and mapping[points[j]]-points[j] == delta:
            last = points[j]; j += 1
        ranges.append((first, last, step, delta)); i = j
    lines = ['/* Generated by scripts/unicode_fold.py; do not edit.',
             ' * Unicode 16.0.0 C+S mappings; Unicode-3.0 license.',
             ' * Source: scripts/data/CaseFolding-16.0.0.txt; licenses/Unicode.txt. */', '#pragma once',
             'static const struct {uint32_t first,last,step;int32_t delta;} vfat_folds[]={']
    lines += [f' {{0x{a:x},0x{b:x},{s},{d}}},' for a,b,s,d in ranges]
    lines += ['};', 'static uint32_t vfat_fold(uint32_t c) {',
              ' unsigned lo=0,hi=sizeof vfat_folds/sizeof vfat_folds[0];',
              ' while(lo<hi) {unsigned mid=lo+(hi-lo)/2;',
              '  if(c<vfat_folds[mid].first)hi=mid;',
              '  else if(c>vfat_folds[mid].last)lo=mid+1;',
              '  else return (c-vfat_folds[mid].first)%vfat_folds[mid].step?c:(uint32_t)((int32_t)c+vfat_folds[mid].delta);',
              ' }', ' return c;', '}', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    target = ROOT/'include/vfat_fold.h'
    target.write_text(generate())
    print(target)
