"""Convert the sandbox-kernel boot art (art/boot/, round 2) into C data: core/logo_data.c.
The kernel has no image decoder, so everything is baked here.
  e-ink: the 96x96 and 40x40 chip-with-K marks from their P4 PBMs (rows msb first, 1 = black).
  HDMI:  the overlay panel (364x96, cut from the 960x540 overlay at 298,312) and the
         recovery header (mark, title, caption: 424x72 at 96,44), as palette runs:
         one byte per run, high nibble = palette index, low nibble = run length - 1.
Usage: scripts/make_boot_art.py            (needs Pillow; reads art/boot/, writes core/logo_data.c)
Never hand-edit the generated file. Art credits are in NOTICE.md."""
import pathlib
from PIL import Image
ROOT = pathlib.Path(__file__).resolve().parent.parent
ART = ROOT / 'art/boot'

def pbm(name):
    head, dims, data = (ART / name).read_bytes().split(b'\n', 2)
    assert head == b'P4'
    w, h = map(int, dims.split())
    stride = (w + 7) // 8
    assert len(data) == stride * h, name
    return w, h, stride, data

def runs(im, box, near_white):
    """Palette-indexed run-length data for the box of an indexed image."""
    rgb = im.convert('RGB').crop(box)
    w, h = rgb.size
    px = [rgb.getpixel((x, y)) for y in range(h) for x in range(w)]
    px = [(255, 255, 255) if p == near_white else p for p in px]
    pal = sorted(set(px), key=lambda c: (c != (0, 0, 0), c))
    assert len(pal) <= 16, len(pal)
    out, i = bytearray(), 0
    while i < len(px):
        n = 1
        while n < 16 and i + n < len(px) and px[i + n] == px[i]: n += 1
        out.append(pal.index(px[i]) << 4 | (n - 1)); i += n
    return w, h, pal, bytes(out)

def arr(name, data, fmt='0x%02x'):
    return f'static const {"uint8_t" if fmt == "0x%02x" else "uint32_t"} {name}[]={{' + ','.join(fmt % b for b in data) + '};'

out = ['/* SPDX-License-Identifier: MIT. Generated by scripts/make_boot_art.py from art/boot/; do not edit. */', '#include "logo.h"']
for name, src in (('large', 'eink-mark-96.pbm'), ('small', 'eink-mark-40.pbm')):
    w, h, stride, data = pbm(src)
    out += [arr(f'{name}_bits', data), f'const struct logo logo_{name}={{{w},{h},{stride},{name}_bits}};']
for tag, src, box in (('panel', 'hdmi-overlay-960x540.png', (298, 312, 662, 408)),
                      ('header', 'hdmi-recovery-console-960x540.png', (96, 44, 520, 116))):
    w, h, pal, data = runs(Image.open(ART / src), box, (0xf8, 0xfc, 0xf8))
    out += [arr(f'{tag}_pal', [(r << 16) | (g << 8) | b for r, g, b in pal], '0x%06x'), arr(f'{tag}_runs', data),
            f'const struct art_runs art_{tag}={{{w},{h},{len(pal)},{len(data)},{tag}_pal,{tag}_runs}};']
(ROOT / 'core/logo_data.c').write_text('\n'.join(out) + '\n')
